// Generates api/contact.ts (the Vercel function) from src/server/contact.ts, the one place the form logic lives.
//
//   npm run sync:api            rewrite api/contact.ts
//   npm run sync:api -- --check exit 1 if api/contact.ts is out of date (used by npm run seo:check)
//
// Why a copy and not an import: the project is "type": "module", and Vercel runs api/contact.ts as plain
// ES modules, where `import ... from '../src/server/contact'` (no file extension) cannot be resolved. The
// function crashed on every request (FUNCTION_INVOCATION_FAILED). The handler has no imports of its own,
// so a self-contained file works everywhere. Do not edit api/contact.ts by hand.
import fs from 'node:fs';

const source = fs.readFileSync(new URL('../src/server/contact.ts', import.meta.url), 'utf8');
const target = new URL('../api/contact.ts', import.meta.url);

if (/^import\s/m.test(source)) {
  console.error('src/server/contact.ts now has an import. The Vercel copy must stay self-contained, so this needs a different approach.');
  process.exit(1);
}

const body = source
  .replace('export interface MailEnv', 'interface MailEnv')
  .replace('export const DEFAULT_TO', 'const DEFAULT_TO')
  .replace('export async function handleContact', 'async function handleContact');

const output = `// GENERATED by scripts/sync-vercel-function.mjs from src/server/contact.ts. Do not edit by hand:
// change the source, then run "npm run sync:api". Vercel Function, runs automatically on Vercel.
${body.trimEnd()}

declare const process: { env: Record<string, string | undefined> };

export function POST(request: Request) {
  return handleContact(request, process.env);
}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('api/contact.ts is out of date. Run: npm run sync:api');
    process.exit(1);
  }
  console.log('api/contact.ts is in sync.');
} else {
  fs.writeFileSync(target, output);
  console.log('Wrote api/contact.ts');
}
